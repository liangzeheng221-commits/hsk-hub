const fs=require('fs'),path=require('path');
const p=path.join(__dirname,'lesson.html');
let s=fs.readFileSync(p,'utf8');
const old='<script src="app-core.js?v=20260817-3">';
const next='<script src="app-core.js?v=20260818-4">';
if((s.split(old).length-1)!==1)throw new Error('Expected exactly one legacy app-core cache key');
s=s.replace(old,next);
if(!s.includes(next))throw new Error('New app-core cache key missing');
fs.writeFileSync(p,s);
console.log(JSON.stringify({status:'APPLIED',appCoreVersion:'20260818-4'}));
