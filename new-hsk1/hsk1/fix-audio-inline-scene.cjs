const fs=require('fs'),path=require('path');
const p=path.join(__dirname,'app-core.js');
let s=fs.readFileSync(p,'utf8');
const before=s;
s=s.replace('onclick="playOfficialTextScene(sceneIndex)"','onclick="playOfficialTextScene(${sceneIndex})"');
s=s.replace('onclick="playOfficialTextLine(sceneIndex,${i})"','onclick="playOfficialTextLine(${sceneIndex},${i})"');
if(s===before)throw new Error('No inline scene-index replacements made');
if(s.includes('onclick="playOfficialTextScene(sceneIndex)"')||s.includes('onclick="playOfficialTextLine(sceneIndex,'))throw new Error('Lexical sceneIndex still exposed to inline handler');
fs.writeFileSync(p,s);
console.log(JSON.stringify({status:'APPLIED',literalSceneIndex:true}));
